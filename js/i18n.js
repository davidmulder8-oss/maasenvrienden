  function updateLangSwitcherUI() {
    var labels = { nl: "NL", en: "EN", de: "DE" };
    document.querySelectorAll(".lang-current").forEach(function (btn) {
      var flagEl = btn.querySelector(".flag");
      if (flagEl) flagEl.innerHTML = FLAG_SVG[currentLang];
      var labelEl = btn.querySelector("[data-lang-label]");
      if (labelEl) labelEl.textContent = labels[currentLang];
    });
    document.querySelectorAll(".lang-option").forEach(function (opt) {
      var isCurrent = opt.getAttribute("data-lang") === currentLang;
      opt.classList.toggle("is-current", isCurrent);
      if (isCurrent) opt.setAttribute("aria-current", "true");
      else opt.removeAttribute("aria-current");
    });
  }

  function applyTranslations() {
    document.documentElement.setAttribute("lang", currentLang);

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      var value = t(el.getAttribute("data-i18n"));
      if (el.hasAttribute("data-i18n-html")) el.innerHTML = value;
      else el.textContent = value;
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach(function (el) {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
    });
    document.querySelectorAll("[data-i18n-alt]").forEach(function (el) {
      el.setAttribute("alt", t(el.getAttribute("data-i18n-alt")));
    });
    document.querySelectorAll("[data-i18n-title]").forEach(function (el) {
      el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
    });

    updateLangSwitcherUI();
  }

  function setLang(lang) {
    if (SUPPORTED.indexOf(lang) === -1 || lang === currentLang) {
      if (SUPPORTED.indexOf(lang) !== -1) return;
    }
    currentLang = lang;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
    applyTranslations();
    document.dispatchEvent(new CustomEvent("mev:langchange", { detail: { lang: lang } }));
  }

  window.MEV_I18N = {
    t: t,
    setLang: setLang,
    getLang: function () { return currentLang; },
    SUPPORTED: SUPPORTED
  };

  document.addEventListener("DOMContentLoaded", applyTranslations);
