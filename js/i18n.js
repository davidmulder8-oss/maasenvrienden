  function getSavedLang() {
    var saved = null;
    try { saved = localStorage.getItem(STORAGE_KEY); } catch (e) {}
    return SUPPORTED.indexOf(saved) !== -1 ? saved : DEFAULT_LANG;
  }

  var currentLang = getSavedLang();

  function t(key) {
    var dict = DICT[currentLang] || DICT[DEFAULT_LANG];
    if (dict && Object.prototype.hasOwnProperty.call(dict, key)) return dict[key];
    var fallback = DICT[DEFAULT_LANG];
    if (fallback && Object.prototype.hasOwnProperty.call(fallback, key)) return fallback[key];
    return key;
  }

